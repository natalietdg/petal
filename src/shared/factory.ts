// A slug from the name, unique among `taken` and never a spine id.
export function newStationId(name: string, taken: readonly string[]): string {
  const base = name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, MAX.id - 4) || 'station';
  let id = base;
  for (let n = 2; taken.includes(id) || isSpineId(id); n++) id = `${base}-${n}`;
  return id;
}

const isRecord = (value: unknown): value is Record<string, unknown> => typeof value === 'object' && value !== null && !Array.isArray(value);
const isRunner = (value: unknown): value is Runner => RUNNERS.some((r) => r === value);
// Files saved before the rename name the approval step 'natalie'; read it as 'you'.
const LEGACY_RUNNERS: Record<string, Runner> = { natalie: 'you' };
const migrateRunner = (value: unknown): unknown => (typeof value === 'string' && Object.hasOwn(LEGACY_RUNNERS, value) ? LEGACY_RUNNERS[value] : value);

// One station, trimmed, unknown keys dropped; a string names what is wrong.
function validateStation(raw: unknown, place: string): Station | string {
  if (!isRecord(raw)) return `${place} isn’t an object.`;
  const text = (key: keyof typeof MAX, required: boolean): string | { problem: string } => {
    const value = raw[key];
    if (value === undefined && !required) return '';
    if (typeof value !== 'string') return { problem: `${place}: ${key} must be text.` };
    const trimmed = value.trim();
    if (required && !trimmed) return { problem: `${place}: ${key} can’t be empty.` };
    if (trimmed.length > MAX[key]) return { problem: `${place}: ${key} is over ${MAX[key]} characters.` };
    return trimmed;
  };
  const id = text('id', true);
  const name = text('name', true);
  const instructions = text('instructions', false);
  const passCheck = text('passCheck', false);
  for (const field of [id, name, instructions, passCheck]) if (typeof field !== 'string') return field.problem;
  const named = `${place} (“${name as string}”)`;
  if (!/^[a-z0-9-]+$/.test(id as string)) return `${named}: id may hold only a–z, 0–9 and dashes.`;
  const runner = migrateRunner(raw.runner);
  if (!isRunner(runner)) return `${named}: who runs it must be one of ${CUSTOM_RUNNERS.join(', ')}.`;
  const station: Station = { id: id as string, name: name as string, instructions: instructions as string, passCheck: passCheck as string, runner };
  const extra = runner === 'subagent' ? 'agentType' : runner === 'script' ? 'command' : null;
  if (extra) {
    const value = text(extra, false);
    if (typeof value !== 'string') return value.problem.replace(place, named);
    if (!value) return `${named}: a ${runner} station needs ${extra === 'agentType' ? 'an agent type' : 'a command'}.`;
    if (/[\r\n]/.test(value)) return `${named}: ${extra === 'agentType' ? 'the agent type' : 'the command'} must be one line.`;
    station[extra] = value;
  }
  return station;
}

// A spine station keeps its id, runner and agent; only its name, instructions and pass check are hers to edit.
function spineOf(station: Station): Station {
  const fixed = SPINE_STATIONS[station.id as SpineId];
  const { agentType: _a, command: _c, ...rest } = station;
  return { ...rest, runner: fixed.runner, ...(fixed.agentType ? { agentType: fixed.agentType } : {}) };
}

// The spine in order, Intake first; custom stations anywhere after Intake.
function spineProblem(stations: readonly Station[]): string | null {
  const order = stations.filter((s) => isSpineId(s.id)).map((s) => s.id);
  if (JSON.stringify(order) !== JSON.stringify(SPINE)) return `The stations must keep ${SPINE_STATIONS.intake.name}, ${SPINE.slice(1).map((id) => SPINE_STATIONS[id].name).join(', ')} once each, in that order.`;
  if (stations[0]?.id !== 'intake') return 'Intake has to come first: it runs in the session where the ask was typed.';
  if (stations.some((s) => !isSpineId(s.id) && s.runner === 'petal')) return 'Only Merge is run by Petal.';
  return null;
}

function validateReviewers(raw: unknown): Reviewer[] | string {
  if (raw === undefined) return DEFAULT_REVIEWERS.map((r) => ({ ...r }));
  if (!Array.isArray(raw) || !raw.length) return 'The factory needs at least one reviewer.';
  const reviewers: Reviewer[] = [];
  for (const [i, r] of raw.entries()) {
    if (!isRecord(r) || typeof r.name !== 'string' || typeof r.agentType !== 'string') return `Reviewer ${i + 1} needs a name and an agent type.`;
    const name = r.name.trim().toLowerCase();
    const agentType = r.agentType.trim();
    if (!/^[a-z0-9-]{1,40}$/.test(name)) return `Reviewer ${i + 1}: the name may hold only a–z, 0–9 and dashes.`;
    if (!agentType || agentType.length > MAX.agentType || /[\r\n]/.test(agentType)) return `Reviewer “${name}”: the agent type must be one short line.`;
    if (reviewers.some((x) => x.name === name)) return `Two reviewers are called “${name}”.`;
    reviewers.push({ name, agentType, when: r.when === 'visual' ? 'visual' : 'always' });
  }
  return reviewers;
}

function validateRisky(raw: unknown): RiskRule[] | string {
  if (raw === undefined) return copyRules(DEFAULT_RISKY);
  if (!Array.isArray(raw)) return 'The risky paths must be a list.';
  const rules: RiskRule[] = [];
  for (const [i, r] of raw.entries()) {
    if (!isRecord(r) || typeof r.label !== 'string' || !r.label.trim() || !Array.isArray(r.patterns)) return `Risky rule ${i + 1} needs a label and a list of paths.`;
    const patterns = r.patterns.filter((p): p is string => typeof p === 'string').map((p) => p.trim()).filter(Boolean);
    if (patterns.some((p) => p.length > 200 || /[\r\n]/.test(p))) return `Risky rule “${r.label.trim()}”: each path must be one short line.`;
    rules.push({ label: r.label.trim().slice(0, 60), patterns });
  }
  return rules;
}

// A version 1 checklist becomes custom stations on the spine. Its Intake and Build become the spine's (her text kept),
// Ship becomes Approve, a review station run by a subagent joins the reviewers, and Review, Approve and Merge go where
// Ship was (or at the end). Stations after Ship stay after Merge.
export function migrateV1(stations: readonly Station[]): { stations: Station[]; reviewers: Reviewer[] } {
  const reviewers = DEFAULT_REVIEWERS.map((r) => ({ ...r }));
  const groups: Record<'preBuild' | 'postBuild' | 'afterShip', Station[]> = { preBuild: [], postBuild: [], afterShip: [] };
  let place: keyof typeof groups = 'preBuild';
  let intake = spineStation('intake');
  let build = spineStation('build');
  for (const s of stations) {
    if (s.id === 'intake') intake = spineOf(s);
    else if (s.id === 'build') { build = spineOf(s); if (place === 'preBuild') place = 'postBuild'; }
    else if (s.id === 'ship' && place !== 'afterShip') place = 'afterShip';
    else if (s.runner === 'subagent' && s.agentType && /review/i.test(s.name)) {
      if (!reviewers.some((r) => r.agentType === s.agentType)) reviewers.push({ name: newStationId(s.agentType, reviewers.map((r) => r.name)), agentType: s.agentType, when: 'always' });
    } else if (!isSpineId(s.id)) groups[place].push(s); // a v1 station sharing a spine id gives way to the spine
  }
  return {
    stations: [intake, ...groups.preBuild, build, ...groups.postBuild, spineStation('review'), spineStation('approve'), spineStation('merge'), ...groups.afterShip],
    reviewers,
  };
}

// A factory as read from disk or sent by the renderer; never throws. A version 1 file comes back migrated.
// Petal counts each session's tokens itself from its transcript, at no token cost, so the Spend check agent station retires.
export const RETIRED_STATION_IDS: readonly string[] = ['token-check'];

export function validateFactory(raw: unknown): Validated {
  if (!isRecord(raw)) return { ok: false, problem: 'The factory isn’t a JSON object.' };
  const version = raw.version ?? 1;
  if (version !== 1 && version !== 2) return { ok: false, problem: `Unknown factory version ${JSON.stringify(raw.version)}.` };
  if (!Array.isArray(raw.stations)) return { ok: false, problem: 'The factory has no stations list.' };
  if (!raw.stations.length) return { ok: false, problem: 'The factory needs at least one station.' };
  if (raw.stations.length > MAX_STATIONS) return { ok: false, problem: `The factory has over ${MAX_STATIONS} stations.` };
  let stations: Station[] = [];
  for (const [i, entry] of raw.stations.entries()) {
    const station = validateStation(entry, `Station ${i + 1}`);
    if (typeof station === 'string') return { ok: false, problem: station };
    if (stations.some((s) => s.id === station.id)) return { ok: false, problem: `Two stations share the id “${station.id}”.` };
    stations.push(station);
  }
  const kept = stations.filter((s) => !RETIRED_STATION_IDS.includes(s.id));
  const retired = kept.length < stations.length;
  stations = kept;
  let reviewers = validateReviewers(raw.reviewers);
  if (typeof reviewers === 'string') return { ok: false, problem: reviewers };
  if (version === 1) ({ stations, reviewers } = migrateV1(stations));
  else stations = stations.map((s) => (isSpineId(s.id) ? spineOf(s) : s));
  const spine = spineProblem(stations);
  if (spine) return { ok: false, problem: spine };
  const risky = validateRisky(raw.risky);
  if (typeof risky === 'string') return { ok: false, problem: risky };
  const cap = raw.reworkCap ?? DEFAULT_REWORK_CAP;
  if (!Number.isInteger(cap) || (cap as number) < 0 || (cap as number) > MAX_REWORK) return { ok: false, problem: `The rework cap must be a whole number from 0 to ${MAX_REWORK}.` };
  return { ok: true, factory: { version: 2, stations, reviewers, reworkCap: cap as number, risky }, migrated: version === 1 || retired };
}

function whoRuns(station: Station): string {
  switch (station.runner) {
    case 'claude': return 'Claude, in this session.';
    case 'subagent': return station.id === 'review' ? 'the reviewers, in parallel.' : `a \`${station.agentType}\` subagent. Brief it with the request and what earlier stations found; check its report against the pass check.`;
    case 'script': return `a script. Run \`${station.command}\` and read its output; Petal never runs it for you.`;
    case 'you': return 'The user. Stop here, show where things stand, and wait for their go-ahead before the next station.';
    case 'petal': return 'Petal. Do not merge or push yourself.';
  }
}

export function renderStations(stations: readonly Station[]): string {
  return stations.map((s, i) => [
    `### ${i + 1}. ${s.name}`,
    '',
    `**Who runs it:** ${whoRuns(s)}`,
    ...(s.instructions ? ['', s.instructions] : []),
    '',
    `**Pass check:** ${s.passCheck || 'none set; say what you checked.'}`,
  ].join('\n')).join('\n\n');
}

const INTRO = 'Every build, feature or fix in a project runs as a factory job: its own branch and its own copy of the repo, reviewers in parallel, and an approval step for risky changes. Petal watches the job’s files and moves the job along; you write the files.';

// The reply line Petal pins as a progress bar in the reader's status strip (shared/station-line.ts parses it).
function stationLineRule(stations: readonly Station[]): string {
  const first = stations[0]?.name ?? 'Intake';
  return `**Station line.** While you work a job, every reply carries exactly one extra line right after its status lines (after **Next:**): \`**Station:** <n>/${stations.length} <station name> · <met or not yet>\`. Use the number and name of the station you are on, as written below, and say \`met\` once its pass check holds, \`not yet\` until then. For example: \`**Station:** 1/${stations.length} ${first} · not yet\`.`;
}

const REPO_KEY_RULE = '`<repoKey>` is the output of `git rev-parse --show-toplevel` with every character that is not a letter or digit replaced by `-` (for example `/home/me/shop` becomes `-home-me-shop`).';

function reviewerLines(reviewers: readonly Reviewer[]): string {
  return reviewers.map((r) => `- \`${r.name}\`: a \`${r.agentType}\` subagent${r.when === 'visual' ? ', only when the diff touches how something looks (CSS, layout, themes, icons, components, renderer files)' : ''}. It writes \`review-${r.name}.md\`.`).join('\n');
}

function riskyLines(risky: readonly RiskRule[]): string {
  return risky.map((r) => `- ${r.label}: ${r.patterns.map((p) => `\`${p}\``).join(', ')}`).join('\n');
}

// The orchestrator: what /factory and its subcommands do, the files and their first lines, then the stations.
function renderOrchestrator(factory: Factory): string {
  return `## Where a job lives

- Job folder: \`~/.petal/repos/<repoKey>/factory/jobs/<job>/\`, where ${REPO_KEY_RULE}
- Its copy of the repo: \`~/.petal/worktrees/<repoKey>/<job>\`, on branch \`factory/<job>\`. Nothing about a job is written inside the repo.
- \`<job>\` is today's date as \`YYYYMMDD\`, a dash, and the ask in lowercase with every run of other characters turned into one dash, at most 28 characters (add \`-2\`, \`-3\` if that folder exists).
- \`job.json\` is Petal's. Read it for the job's \`state\`, \`stations\`, \`reviewers\`, \`rework\` and \`guidance\`; never write it. After you write a hand-off file, wait a few seconds and read \`state\` again: Petal moves the job from your files.

## Hand-off files

Each file's first line is what Petal reads. Write the first line exactly, then whatever detail helps.

| File | First line | Written at |
|---|---|---|
| \`request.md\` | \`STATUS: intake\`, then \`Repo: <git toplevel>\`, \`Session: <this session's id, if known>\`, a blank line, the ask | /factory |
| \`spec.md\` | \`STATUS: ready\`, or \`STATUS: confirm\` when you asked questions at Intake | Intake |
| \`build.md\` | \`STATUS: working\`, then \`STATUS: done · <one line>\` or \`STATUS: blocked · <why>\` | Build |
| \`review-<name>.md\` | \`VERDICT: PASS\` or \`VERDICT: FAIL · <the main problem>\` | Review |
| \`decision.md\` | \`VERDICT: PASS\` or \`VERDICT: FAIL · <note>\` | approve, rework |

## Commands

**/factory <ask>.** Runs Intake here, in this session, because this is where the user is.
1. Make the job folder and write \`request.md\`.
2. Intake: restate the ask, list the acceptance checks, and ask every question at once (one AskUserQuestion). Unless the ask is small enough for three stations or fewer, call the \`token\` agent once to name the model for each role (builder, each reviewer) and write its picks under \`## Models\` in \`spec.md\`.
3. Write \`spec.md\`. Its first line is \`STATUS: confirm\` if you asked questions, so the user checks the spec before building; otherwise \`STATUS: ready\`.
4. Read \`state\`. \`building\`: Petal has started the job in its own copy; tell the user it is running and go back to what they were doing. \`queued\`: two jobs already run in this repo; Petal starts it when one finishes. \`spec\`: say \`/factory approve <job>\` starts it.

**Runners.** Petal makes each job's copy and starts its runner (a headless Claude in that copy running \`/factory run <job>\`) whenever the job enters Build, a rework the user asked for, or a fresh review. Never start one yourself, and never create the copy. Petal shows progress and calls the user when a job needs them.

**/factory next.** Petal starts queued jobs on its own, oldest first, as slots free. List the job folders and say where each queued job stands. If the oldest has no \`spec.md\`, run Intake for it here, as for /factory <ask>.

**/factory approve <job>.** At \`spec\`: change the first line of \`spec.md\` to \`STATUS: approved\`. At \`approve\`: write \`decision.md\` with \`VERDICT: PASS\`, and Petal merges. At \`escalated\` (the user fixed it by hand): write \`decision.md\` with \`VERDICT: PASS\`, and Petal sends it back to review.

**/factory rework <job> <note>.** Write \`decision.md\` with \`VERDICT: FAIL · <note>\`. Petal restarts the builder, and the note reaches it as \`guidance\`.

**/factory run <job>.** The job's runner, in its copy. Loop on \`state\`:
- \`building\` or \`rework\`: write \`build.md\` with \`STATUS: working\`. Run the stations between Build and Review in \`stations\`, in order, then Build itself with a subagent briefed with \`spec.md\`, the \`guidance\` and any \`round-*/review-*.md\` from earlier rounds. Commit on \`factory/<job>\` and run the project's unit tests in this copy. Then set \`build.md\` to \`STATUS: done · <one line>\`, or \`STATUS: blocked · <why>\` if it can't be done.
- \`reviewing\`: \`git diff --name-only <main branch>...factory/<job>\` lists the changed files. Start every reviewer that applies in one message, all at once, each briefed with \`spec.md\` and the diff, each writing its own review file.
- \`rework\` again: Petal moved the last round's files into \`round-<n>/\`; build again from their verdicts.
- \`approve\`, \`escalated\`, \`merging\`, \`done\`, \`discarded\`: stop. The user or Petal takes it from here.

## Rules

- Never merge, push or touch the main checkout. Petal merges into main on this computer (only when that checkout has nothing uncommitted) or pushes the job branch and stops at a pull request, as the repo's ship mode says.
- A job keeps the stations, reviewers and risky paths it started with: read them from \`job.json\`, not from below.
- After ${factory.reworkCap} reworks a failing review goes to the user (\`escalated\`).
- A change touching any of these paths waits for the user's approval before it merges:
${riskyLines(factory.risky)}

## Reviewers

${reviewerLines(factory.reviewers)}`;
}

