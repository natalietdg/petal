export const defaultFactory = (): Factory => ({ version: 1, stations: DEFAULT_STATIONS.map((s) => ({ ...s })) });

// The badge on a card.
export function runnerLabel(station: Pick<Station, 'runner' | 'agentType'>): string {
  switch (station.runner) {
    case 'claude': return 'Claude';
    case 'subagent': return station.agentType ? `Subagent · ${station.agentType}` : 'Subagent';
    case 'script': return 'Script';
    case 'natalie': return 'Natalie approves';
  }
}

// A slug from the name, unique among `taken`.
export function newStationId(name: string, taken: readonly string[]): string {
  const base = name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, MAX.id - 4) || 'station';
  let id = base;
  for (let n = 2; taken.includes(id); n++) id = `${base}-${n}`;
  return id;
}

const isRecord = (value: unknown): value is Record<string, unknown> => typeof value === 'object' && value !== null && !Array.isArray(value);
const isRunner = (value: unknown): value is Runner => RUNNERS.some((r) => r === value);

// One station, trimmed, unknown keys dropped; a string names what is wrong.
function validateStation(raw: unknown, place: string): Station | string {
  if (!isRecord(raw)) return `${place} isn’t an object.`;
  const text = (key: keyof typeof MAX, required: boolean): string | { problem: string } => {
    const value = raw[key];
    if (value === undefined && !required) return '';
    if (typeof value !== 'string') return { problem: `${place}: ${key} must be text.` };
    const trimmed = value.trim();
    if (required && !trimmed) return { problem: `${place}: ${key} can’t be empty.` };
    if (trimmed.length > MAX[key]) return { problem: `${place}: ${key} is over ${MAX[key]} characters.` };
    return trimmed;
  };
  const id = text('id', true);
  const name = text('name', true);
  const instructions = text('instructions', false);
  const passCheck = text('passCheck', false);
  for (const field of [id, name, instructions, passCheck]) if (typeof field !== 'string') return field.problem;
  const named = `${place} (“${name as string}”)`;
  if (!/^[a-z0-9-]+$/.test(id as string)) return `${named}: id may hold only a–z, 0–9 and dashes.`;
  if (!isRunner(raw.runner)) return `${named}: who runs it must be one of ${RUNNERS.join(', ')}.`;
  const station: Station = { id: id as string, name: name as string, instructions: instructions as string, passCheck: passCheck as string, runner: raw.runner };
  const extra = raw.runner === 'subagent' ? 'agentType' : raw.runner === 'script' ? 'command' : null;
  if (extra) {
    const value = text(extra, false);
    if (typeof value !== 'string') return value.problem.replace(place, named);
    if (!value) return `${named}: a ${raw.runner} station needs ${extra === 'agentType' ? 'an agent type' : 'a command'}.`;
    if (/[\r\n]/.test(value)) return `${named}: ${extra === 'agentType' ? 'the agent type' : 'the command'} must be one line.`;
    station[extra] = value;
  }
  return station;
}

// A factory as read from disk or sent by the renderer; never throws.
export function validateFactory(raw: unknown): Validated {
  if (!isRecord(raw)) return { ok: false, problem: 'The factory isn’t a JSON object.' };
  if (raw.version !== undefined && raw.version !== 1) return { ok: false, problem: `Unknown factory version ${JSON.stringify(raw.version)}.` };
  if (!Array.isArray(raw.stations)) return { ok: false, problem: 'The factory has no stations list.' };
  if (!raw.stations.length) return { ok: false, problem: 'The factory needs at least one station.' };
  if (raw.stations.length > MAX_STATIONS) return { ok: false, problem: `The factory has over ${MAX_STATIONS} stations.` };
  const stations: Station[] = [];
  for (const [i, entry] of raw.stations.entries()) {
    const station = validateStation(entry, `Station ${i + 1}`);
    if (typeof station === 'string') return { ok: false, problem: station };
    if (stations.some((s) => s.id === station.id)) return { ok: false, problem: `Two stations share the id “${station.id}”.` };
    stations.push(station);
  }
  return { ok: true, factory: { version: 1, stations } };
}

function whoRuns(station: Station): string {
  switch (station.runner) {
    case 'claude': return 'Claude, in this session.';
    case 'subagent': return `a \`${station.agentType}\` subagent. Brief it with the ticket and what earlier stations found; check its report against the pass check.`;
    case 'script': return `a script. Run \`${station.command}\` and read its output; Petal never runs it for you.`;
    case 'natalie': return 'Natalie. Stop here, show where things stand, and wait for her go-ahead before the next station.';
  }
}

function renderStations(stations: readonly Station[]): string {
  return stations.map((s, i) => [
    `## ${i + 1}. ${s.name}`,
    '',
    `**Who runs it:** ${whoRuns(s)}`,
    ...(s.instructions ? ['', s.instructions] : []),
    '',
    `**Pass check:** ${s.passCheck || 'none set; say what you checked.'}`,
  ].join('\n')).join('\n\n');
}

const INTRO = 'Follow these stations in order for every build, feature or fix request. A station is done only when its pass check holds; say which station you are on as you go.';

// global: SKILL.md with frontmatter (Claude Code reads it from line 1), the marker as the first body line.
// project: <repo>/.petal/factory.md, the marker on line 1.
export function renderSkill(factory: Factory, scope: 'global' | 'project', projectName?: string): string {
  const body = [
    GENERATED_MARKER,
    '',
    scope === 'project' ? `# Software factory for ${projectName ?? 'this project'}` : '# Software factory',
    '',
    INTRO,
    ...(scope === 'global' ? ['', 'If the project you are working in has `.petal/factory.md` at its root, follow that file instead of the stations below.'] : []),
    '',
    renderStations(factory.stations),
    '',
  ].join('\n');
  if (scope === 'project') return body;
  return `---\nname: ${SKILL_NAME}\ndescription: ${JSON.stringify(SKILL_DESCRIPTION)}\n---\n${body}`;
}

// True when Petal wrote this text: the marker is its first line, or the first after frontmatter.
export function isGenerated(text: string): boolean {
  const lines = text.replace(/^\uFEFF/, '').split(/\r?\n/);
  let first = 0;
  if (lines[0] === '---') {
    const end = lines.indexOf('---', 1);
    if (end === -1) return false;
    first = end + 1;
  }
  return lines[first] === GENERATED_MARKER;
}
