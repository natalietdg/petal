// The software factory: ordered stations every build, feature or fix goes through, and the skill text Claude reads.
// Pure: main/factory-store.ts reads and writes the files, renderer/workflow-factory.ts edits the stations.

export const RUNNERS = ['claude', 'subagent', 'script', 'natalie'] as const;
export type Runner = (typeof RUNNERS)[number];

export interface Station {
  id: string;
  name: string;
  instructions: string;
  passCheck: string;
  runner: Runner;
  agentType?: string; // runner 'subagent' only
  command?: string; // runner 'script' only; Claude runs it, Petal never does
}

export interface Factory {
  version: 1;
  stations: Station[];
}

export type Validated = { ok: true; factory: Factory } | { ok: false; problem: string };

export const MAX_STATIONS = 30;
const MAX = { id: 40, name: 80, instructions: 4000, passCheck: 1000, agentType: 80, command: 500 };

